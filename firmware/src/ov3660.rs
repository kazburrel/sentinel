//! OV3660 SCCB register init sequence, ported from Espressif's own
//! `esp32-camera` library (sensors/ov3660.c, sensors/private_include/
//! ov3660_settings.h) -- extracted programmatically (not hand-transcribed)
//! to avoid transcription errors, with symbolic register names resolved
//! to their real addresses. Comment-only entries in the source (a disabled
//! alternate gamma table) are correctly excluded.
//!
//! Uses SCCB's 16-bit register addressing (unlike OV2640's 8-bit), matching
//! `SCCB_Write16`/`SCCB_Read16` in the reference driver: a plain I2C write of
//! [reg_hi, reg_lo, value], or [reg_hi, reg_lo] followed by a 1-byte read.

