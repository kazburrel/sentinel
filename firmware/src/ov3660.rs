/// Which crop/scale register table to apply during `init_jpeg`.
#[derive(Debug, Clone, Copy)]
pub enum Framesize {
    /// 640x480.
    Vga,
    /// 1600x1200 -- full-resolution sensor readout (no 2x2 binning),
    /// scaled by the ISP to 1600x1200 output.
    Uxga,
}

#[derive(Debug)]
pub enum CheckIdError {
    I2c(esp_hal::i2c::master::Error),
    Mismatch(u16),
}

pub struct Ov3660<'d> {
    i2c: I2c<'d, Blocking>,
}

impl<'d> Ov3660<'d> {
    pub fn new(i2c: I2c<'d, Blocking>) -> Self {
        Self { i2c }
    }

    fn write_reg(&mut self, reg: u16, value: u8) -> Result<(), esp_hal::i2c::master::Error> {
        let hi = (reg >> 8) as u8;
        let lo = (reg & 0xFF) as u8;
        self.i2c.write(OV3660_ADDRESS, &[hi, lo, value])
    }

    fn read_reg(&mut self, reg: u16) -> Result<u8, esp_hal::i2c::master::Error> {
        let hi = (reg >> 8) as u8;
        let lo = (reg & 0xFF) as u8;
        self.i2c.write(OV3660_ADDRESS, &[hi, lo])?;
        let mut buf = [0u8; 1];
        self.i2c.read(OV3660_ADDRESS, &mut buf)?;
        Ok(buf[0])
    }

    async fn write_table(&mut self, table: &[(u16, u16)]) -> Result<(), esp_hal::i2c::master::Error> {
        for &(reg, val) in table {
            if reg == REGLIST_TAIL {
                break;
            }
            if reg == REG_DLY {
                Timer::after(Duration::from_millis(val as u64)).await;
            } else {
                self.write_reg(reg, val as u8)?;
            }
        }
        Ok(())
    }

    /// Reads the 16-bit product ID (registers 0x300A/0x300B) and confirms
    /// it matches the real OV3660 PID (0x3660), rather than assuming.
    pub fn check_id(&mut self) -> Result<(), CheckIdError> {
        let hi = self.read_reg(0x300A).map_err(CheckIdError::I2c)?;
        let lo = self.read_reg(0x300B).map_err(CheckIdError::I2c)?;
        let pid = ((hi as u16) << 8) | (lo as u16);
        if pid != OV3660_PID {
            return Err(CheckIdError::Mismatch(pid));
        }
        Ok(())
    }

    /// Runs the sensor's default register init sequence, then switches it
    /// into JPEG output mode, then sets JPEG quality (registers taken
    /// directly from the reference `reset()`/`set_pixformat()`/
    /// `set_quality()` functions in ov3660.c).
    pub async fn init_jpeg(
        &mut self,
        quality: u8,
        framesize: Framesize,
    ) -> Result<(), esp_hal::i2c::master::Error> {
        self.write_reg(0x3008, 0x82)?; // software reset
        Timer::after(Duration::from_millis(100)).await;

        self.write_table(OV3660_DEFAULT_REGS).await?;
        Timer::after(Duration::from_millis(100)).await;

        self.write_table(OV3660_FMT_JPEG).await?;

        // COMPRESSION_CTRL07 = 0x4407, Bit[5:0]: QS (quality scale)
        self.write_reg(0x4407, quality & 0x3F)?;

        let framesize_regs = match framesize {
            Framesize::Vga => OV3660_FRAMESIZE_VGA,
            Framesize::Uxga => OV3660_FRAMESIZE_UXGA,
        };
        self.write_table(framesize_regs).await?;

        Ok(())
    }
}
